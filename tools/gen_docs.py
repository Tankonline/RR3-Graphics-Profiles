#!/usr/bin/env python3
"""Regenerate docs/PRESETS.md and docs/SETTINGS_REFERENCE.md from profiles/decompiled.

    python tools/gen_docs.py

Standard library only. Output is deterministic, so re-running it on unchanged profiles gives
identical files (CI or a reviewer can check that the docs match the data).
"""
from __future__ import annotations

import collections
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import rr3gfx  # noqa: E402  (reuses its entity / DTD refusal before any XML parsing)
EDS = ROOT / "profiles" / "decompiled" / "eds"
FEATS = ROOT / "profiles" / "decompiled" / "feats"
DOCS = ROOT / "docs"

HDR_B = ["USE_HDR_POST_PROCESS", "TONEMAP", "GAMMA_CORRECTION"]
HDR_C = HDR_B + ["ENV_MAP_HDR", "USE_HDR_AUTOMATIC_EXPOSURE"]

# Results of on-device testing (Samsung SM-S948B, Adreno 840, Android 16, RR3 14.0.1 ROW),
# each preset copied unmodified over every Android tier. See docs/HDR_BLACK_SCREEN.md.
DEVICE_TESTS = {
    "AndroidXtraHigh": "works", "SimRigTV": "works", "AppleTV": "works", "AppleTV5,3": "works", "iPad": "works",
    "AndroidLow": "black", "AndroidMid": "black", "AndroidMid2": "black", "AndroidHigh": "black",
    "AndroidUltraWide": "black", "iPad1,1": "black", "iPad2,1": "black", "iPad2,2": "black", "iPad2,3": "black",
    "iPad2,5": "black", "iPad3,1": "black", "iPad3,2": "black",
}

# Short explanations only where the meaning has been confirmed (by device testing or by
# RR3's own log output). Everything else is left blank rather than guessed.
CONFIRMED = {
    "USE_HDR_POST_PROCESS": "HDR post-processing pass. Off = black screen on Adreno 840 (needs TONEMAP + GAMMA_CORRECTION too).",
    "TONEMAP": "Tonemapping of the HDR image. Part of HDR fix level B.",
    "GAMMA_CORRECTION": "Gamma correction pass. Part of HDR fix level B.",
    "ENV_MAP_HDR": "HDR environment (reflection) maps. Part of HDR fix level C.",
    "USE_HDR_AUTOMATIC_EXPOSURE": "Automatic exposure for HDR. Part of HDR fix level C.",
    "PLIST_IDENTIFIER": "Preset name. RR3 loads the .feats file named after this value.",
    "ALL_PLISTS": "List of every preset RR3 knows about (identical in all files).",
    "3D_SCENE_SCALE": "Stored as 1.0 everywhere; RR3 computes the real scale at runtime from the screen size (logged as 3DSceneScale).",
    "EXPECTED_RENDERER": "OpenGL ES version the preset targets.",
    "R4_TRACK_EXTENSION": "Track asset sub-folder (low/ = low-detail tracks). Not the cause of the black screen.",
}


def plist_entries(path: Path):
    """[(key, type, value_text)] in file order."""
    data = path.read_bytes()
    rr3gfx.check_text(data, "plist", path.name)
    d = ET.fromstring(data).find("dict")
    items = list(d)
    out = []
    for k, v in zip(items[0::2], items[1::2]):
        if v.tag in ("true", "false"):
            out.append((k.text, "bool", v.tag))
        else:
            out.append((k.text, v.tag, (v.text or "").replace("\r\n", "\n")))
    return out


def feats_entries(path: Path):
    data = path.read_bytes()
    rr3gfx.check_text(data, "feats", path.name)
    dev = ET.fromstring(data).find("Device")
    items = list(dev)
    return [(k.text, v.text) for k, v in zip(items[0::2], items[1::2])]


def cell(text: str, limit: int = 60) -> str:
    text = text.replace("\n", " / ").replace("|", "\\|")
    if text == "":
        return "*(empty)*"
    return text if len(text) <= limit else text[: limit - 1] + "…"


def ranked(counter):
    """(value, count) pairs, most common first. Ties are broken by value, so the output never depends on
    the order the files were read in (which differs between Windows and Linux)."""
    return sorted(counter.items(), key=lambda vc: (-vc[1], vc[0]))


def sort_key(name: str):
    """Android first, then Apple families, natural number order (iPad2,1 < iPad10,1)."""
    family = 0 if name.startswith("Android") else 1 if name == "SimRigTV" else 2
    base = name.rstrip("0123456789,")
    nums = tuple(int(x) for x in name[len(base):].split(",") if x) if name[len(base):] else ()
    return family, base, nums


def presets_md(plists, feats) -> str:
    names = sorted(plists, key=sort_key)
    lines = [
        "# Presets",
        "",
        "_Generated by `tools/gen_docs.py` from `profiles/decompiled`. Do not edit by hand._",
        "",
        f"RR3 14.0.1 ships **{len(plists)} render presets** (`eds/*.plist`) and **{len(feats)} shader feature files** "
        "(`feats/*.feats`). Each preset has a feats file of the same name; `mac.feats` has no preset and is not used "
        "on Android.",
        "",
        "Column guide:",
        "",
        "- **HDR**: `on` when all five HDR switches are on (`USE_HDR_POST_PROCESS`, `TONEMAP`, `GAMMA_CORRECTION`, "
        "`ENV_MAP_HDR`, `USE_HDR_AUTOMATIC_EXPOSURE`), `off` when all five are off. RR3 14.0.1 has no mixed presets.",
        "- **Tested**: result on a Samsung SM-S948B (Adreno 840, Android 16) with the preset copied unmodified. "
        "`black` = black screen after loading. Blank = not tested. See [HDR_BLACK_SCREEN.md](HDR_BLACK_SCREEN.md).",
        "- **Features on**: shader features switched on in the matching `.feats` file (out of 190).",
        "",
        "| Preset | Description | Notes | Screen | GUI layout | Renderer | AA | HDR | Tested | Features on |",
        "|---|---|---|---|---|---|---|---|---|---|",
    ]
    hdr_on = 0
    for n in names:
        s = {k: v for k, _, v in plists[n]}
        flags = {s[k] for k in HDR_C}
        hdr = "on" if flags == {"true"} else "off" if flags == {"false"} else "mixed"
        hdr_on += hdr == "on"
        on = sum(v == "true" for _, v in feats.get(n, []))
        lines.append(
            f"| `{n}` | {cell(s.get('DEVICE_DESCRIPTION', ''), 40)} | {cell(s.get('Notes:', ''), 50)} | "
            f"{s.get('EXPECTED_SCREEN_WIDTH', '?')}x{s.get('EXPECTED_SCREEN_HEIGHT', '?')} | "
            f"{cell(s.get('GUI_LAYOUT_EXTENSION', ''), 20)} | {s.get('EXPECTED_RENDERER', '?')} | {s.get('AA_LEVEL', '?')} | "
            f"{hdr} | {DEVICE_TESTS.get(n, '')} | {on} |")
    lines += [
        "",
        f"**{hdr_on} of {len(names)} presets have HDR on.** Every device test matched the rule "
        "\"HDR off = black screen\" on the Adreno 840.",
        "",
        "## Android tiers",
        "",
        "RR3 picks one of these by itself on Android (this phone is detected as `AndroidHigh`):",
        "`AndroidLow`, `AndroidMid`, `AndroidMid2`, `AndroidHigh`, `AndroidXtraHigh`, `AndroidUltraWide`. "
        "`SimRigTV` is a high-end preset used for EA's simulator rigs. A \"universal override\" copies one preset's "
        "bytes over all seven names; RR3 logs `invalid ID` for the renamed copies but still uses them.",
        "",
    ]
    return "\n".join(lines)


def settings_md(plists, feats) -> str:
    n_p, n_f = len(plists), len(feats)
    order = [k for k, _, _ in next(iter(plists.values()))]
    types = {k: t for entries in plists.values() for k, t, _ in entries}
    lines = [
        "# Settings reference",
        "",
        "_Generated by `tools/gen_docs.py` from `profiles/decompiled`. Do not edit by hand._",
        "",
        "Every key that appears in RR3 14.0.1's graphics profiles, with the values used across all shipped presets. "
        "The **Confirmed meaning** column is only filled in where the behaviour has been confirmed by device testing "
        "or by RR3's own logs. Key names are often self-explanatory, but untested guesses are deliberately left out.",
        "",
        f"## Render settings (`eds/*.plist`): {len(order)} keys, present in all {n_p} presets",
        "",
        "Keys are listed in file order (alphabetical, as RR3 writes them). Multi-line strings are shown with ` / ` "
        "between lines.",
        "",
        "| Key | Type | Values (number of presets) | Confirmed meaning |",
        "|---|---|---|---|",
    ]
    for k in order:
        vals = collections.Counter(dict((kk, v) for kk, _, v in e).get(k, "<missing>") for e in plists.values())
        if len(vals) > 5:
            shown = f"{len(vals)} different values, e.g. " + ", ".join(f"`{cell(v, 30)}`" for v, _ in ranked(vals)[:3])
        else:
            shown = ", ".join(f"`{cell(v, 45)}` ({c})" for v, c in ranked(vals))
        lines.append(f"| `{k}` | {types[k]} | {shown} | {CONFIRMED.get(k, '')} |")

    forder = [k for k, _ in next(iter(feats.values()))]
    lines += [
        "",
        f"## Shader features (`feats/*.feats`): {len(forder)} keys, present in all {n_f} files",
        "",
        "All feats files contain the same keys in the same order; only the true/false values differ. "
        "**Off in** lists the files where the feature is off when that is the minority (otherwise **On in**).",
        "",
        "| # | Key | On in (of " + str(n_f) + ") | Exceptions |",
        "|---|---|---|---|",
    ]
    for i, k in enumerate(forder, 1):
        on = sorted((n for n, e in feats.items() if dict(e)[k] == "true"), key=sort_key)
        off = sorted((n for n, e in feats.items() if dict(e)[k] != "true"), key=sort_key)
        if not off:
            exc = "on everywhere"
        elif not on:
            exc = "off everywhere"
        elif len(off) <= len(on):
            exc = "off in " + ", ".join(f"`{n}`" for n in off) if len(off) <= 12 else f"off in {len(off)} files"
        else:
            exc = "on in " + ", ".join(f"`{n}`" for n in on) if len(on) <= 12 else f"on in {len(on)} files"
        lines.append(f"| {i} | `{k}` | {len(on)} | {exc} |")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    # Sorted by name (a case-sensitive string sort, so it's identical on every OS).
    plists = {p.stem: plist_entries(p) for p in sorted(EDS.glob("*.plist"), key=lambda p: p.name)}
    feats = {p.stem: feats_entries(p) for p in sorted(FEATS.glob("*.feats"), key=lambda p: p.name)}
    if not plists or not feats:
        print("profiles/decompiled is empty - run: python tools/rr3gfx.py decompile profiles/compiled -o profiles/decompiled")
        return 1
    DOCS.mkdir(exist_ok=True)
    for name, text in (("PRESETS.md", presets_md(plists, feats)), ("SETTINGS_REFERENCE.md", settings_md(plists, feats))):
        # open(newline=...) instead of Path.write_text(newline=...), which only exists from Python 3.10.
        with open(DOCS / name, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print(f"wrote docs/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
